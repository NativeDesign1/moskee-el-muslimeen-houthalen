// Rebuild with: node scripts/build-quran-index.mjs [directory of cached <surah>.json arrays]
// Source and terms: https://quranenc.com/nl/home/api (dutch_center, Nederlands Islamitisch
// Centrum / Rowwad Translation Center). Only search fingerprints are distributed here.
// The screen obtains current, unmodified translations, notes and release metadata at runtime.
import { readFile, writeFile } from 'node:fs/promises';
import { excerptBits, FILTER_BITS, normalizeQuranArabic, verseFingerprint } from '../lib/quran-text.js';

const cache = process.argv[2];
const hashes = [];
const filter = Buffer.alloc(FILTER_BITS / 8);
let count = 0;
for (let s = 1; s <= 114; s++) {
  let rows;
  if (cache) {
    rows = JSON.parse(await readFile(cache + '/' + s + '.json', 'utf8'));
  } else {
    const response = await fetch('https://quranenc.com/api/v1/translation/sura/dutch_center/' + s);
    if (!response.ok) throw new Error('Failed to read surah ' + s);
    rows = (await response.json()).result;
  }
  if (!Array.isArray(rows) || !rows.length) throw new Error('Missing surah ' + s);
  const words = [];
  hashes.push(rows.map((row, i) => {
    const source = normalizeQuranArabic(row.arabic_text);
    if (row.sura !== String(s) || row.aya !== String(i + 1) || row.id !== String(++count) || !source) {
      throw new Error('Unexpected QuranEnc source at ' + s + ':' + (i + 1));
    }
    words.push(...source.split(' '));
    return verseFingerprint(source);
  }));
  // Also protect speech fragments spanning the boundary between two verses of a surah.
  for (let i = 0; i + 4 <= words.length; i++) {
    excerptBits(words.slice(i, i + 4).join(' '), bit => {
      filter[bit >>> 3] |= 1 << (bit & 7);
      return true;
    });
  }
}
if (count !== 6236) throw new Error('Expected 6236 ayat');
const header = '// Derived from the Arabic verse records at QuranEnc.com (dutch_center).\n' +
  '// Generated by scripts/build-quran-index.mjs. Entries are non-authoritative search fingerprints.\n';
const format = row => {
  const lines = [];
  for (let i = 0; i < row.length; i += 12) lines.push('    ' + row.slice(i, i + 12).join(', ') + ',');
  return '  [\n' + lines.join('\n') + '\n  ],';
};
await writeFile(new URL('../lib/quran-fingerprints.js', import.meta.url),
  header + 'export const fingerprints = [\n' + hashes.map(format).join('\n') + '\n];\n');
const blocks = filter.toString('base64').match(/.{1,128}/g);
await writeFile(new URL('../lib/quran-excerpts.js', import.meta.url),
  header + 'export const excerptFilter = [\n' + blocks.map(b => "  '" + b + "',").join('\n') + "\n].join('');\n");
